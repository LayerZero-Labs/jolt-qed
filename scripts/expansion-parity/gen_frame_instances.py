#!/usr/bin/env python3
"""Generate JoltBytecode/Inlines/FrameInstances.lean.

The file gives, for each of the twelve in-scope inlines, the write set of its generated
rows, the static frame check `Program.WritesWithin`, the pool-reset check and the frame
corollary of `JoltISA.Inlines.frame_of_run` (JoltBytecode/Inlines/Frame.lean).

The script reads the generated rows in JoltBytecode/Inlines/Generated/<Name>.lean (written
by the expansion-parity driver) and derives everything else from them: the pool registers
each variant writes, its store rows, and which final chunks hold the last write of every
pool register. It asserts that the pool registers each variant writes form a range
from vr48 (so no row writes vr40..47) and that every store base is an architectural
register. The `rfl` checks in the generated file reject any row that writes an
architectural register other than x0.

It emits the `rd != x0` case of every inline and the `rd = x0` case of the five hash
inlines. It omits the `rd = x0` case of the seven secp256k1 inlines: those store through
vr40 before any row writes it. Decision D7 of docs/inline-precompiles.md excludes those
encodings. At the generated-row Jolt pin a6b6dc717 Jolt still accepts them; the open pull
request a16z/jolt#2414 adds the rejection upstream.

Usage, from the repository root:

    python3 scripts/expansion-parity/gen_frame_instances.py          # rewrite the file
    python3 scripts/expansion-parity/gen_frame_instances.py --check  # exit 1 if it differs

After regenerating, build with `lake build JoltBytecode.Inlines.FrameInstances`.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "JoltBytecode/Inlines/FrameInstances.lean"
names=["Sha256","Sha256Init","Keccak256","Keccak256AbsorbPermute","Blake2","Secp256k1Mulq","Secp256k1Mulr","Secp256k1Squareq","Secp256k1Squarer","Secp256k1Divq","Secp256k1Divr","Secp256k1GlvrAdv"]
out=[]
out.append("import JoltBytecode.Inlines.Frame")
for n in names: out.append(f"import JoltBytecode.Inlines.Generated.{n}")
out.append('''
/-!
# Write sets of the twelve in-scope inlines

Generated by `scripts/expansion-parity/gen_frame_instances.py`; do not edit by hand.

For each in-scope inline this file gives the write set, the store slots of the generated
rows, the static frame check `Program.WritesWithin` and the pool-reset check, and the
frame corollary. It covers the `rd ≠ x0` case of all twelve inlines and the `rd = x0` case
of the five hash inlines. The `rd = x0` case of the seven secp256k1 inlines is omitted:
those rows store through `vr40` before any row writes it, so they fail the store-base
check. Decision D7 of `docs/inline-precompiles.md` excludes those encodings. At the
generated-row Jolt pin `a6b6dc717` Jolt still accepts them; the open pull request
a16z/jolt#2414 adds the rejection upstream.

The write sets are exact: `vregs` lists the pool registers the rows write (always a
contiguous range from `vr48`), `xregs` is empty, and `stores` lists the store rows.
No row writes an instruction temporary `vr40..47` or an architectural register.

The checks run chunk by chunk. Each `_chunkN` lemma checks one generated chunk (about
100 rows) by `rfl`, and `Program.rowsWithin_seq_append`, `Program.storeSlots_seq_append`
and `Program.resetsPoolCheck_seq_append` assemble the chunks. `rfl` works although the
rows take free register parameters: with `xregs = []` the checks never compare two
architectural registers. A single `rfl` or `decide` on a whole program exceeds the
default recursion depth, and checking every chunk inside one declaration exceeds the
default heartbeat budget for the 31- and 32-chunk Keccak programs.
-/

open Sail Sail.ConcurrencyInterfaceV1 Sail.ConcurrencyInterfaceV1.PreSail LeanRV64D
  LeanRV64D.Functions

set_option autoImplicit false

noncomputable section

namespace JoltISA.Inlines.FrameInstances

open JoltISA.Inlines.Generated

/-- The pool registers `vr48 .. vr(48 + n - 1)`.
Example: `poolVRegs 2 = [vr48, vr49]`. -/
def poolVRegs (n : Nat) : List VReg := (List.range n).map fun k => BitVec.ofNat 7 (48 + k)
''')
def lc(n): return n[0].lower()+n[1:]
for n in names:
    src=(ROOT/f"JoltBytecode/Inlines/Generated/{n}.lean").read_text()
    adv = "(advice : Nat → BitVec 64)" in src.split("RowsAuto (")[1].split(":=")[0]
    variants=[("rd ≠ x0","","(rs1 rs2 rs3 : regidx)","rs1 rs2 rs3")]
    if not n.startswith("Secp256k1"):
        variants.append(("rd = x0","RdZero","(rs1 rs2 : regidx)","rs1 rs2"))
    for variant,suffix,params,args in variants:
        if adv:
            params=params+" (advice : Nat → BitVec 64)"; args=args+" advice"
        prog=f"{lc(n)}RowsAuto{suffix}"
        nm=f"{lc(n)}{suffix}"
        defs=[d for d in re.split(r'\ndef ',src) if re.match(prog+r'Chunk\d+ ',d)]
        nch=len(defs)
        assert [re.match(r'(\w+) ',d).group(1) for d in defs]==[f"{prog}Chunk{i}" for i in range(nch)]
        listdef=[d for d in re.split(r'\ndef ',src) if d.startswith(prog+"List ")][0]
        assert listdef.count("++")==nch-1
        dst=set(); slots=[]; chunk_slots=[]; last_write={}
        for ci,d in enumerate(defs):
            cs=[]; chunk_slots.append(cs)
            for line in d.split('\n'):
                line=line.strip()
                m=re.match(r'\.(SD|VirtualStore[BHW]) \((\.xreg \w+|\.vreg \(BitVec\.ofNat 7 \d+\))\) .*?\((\w+) : BitVec 64\)',line)
                if m:
                    base=m.group(2)
                    assert base.startswith(".xreg "),(n,variant,line)
                    sl=f"⟨{base}, {m.group(3)}, .{'dword' if m.group(1)=='SD' else 'floor'}⟩"
                    slots.append(sl); cs.append(sl)
                    continue
                mm=re.match(r'\.(\w+) (?:\.normal )?\(\.vreg \(BitVec\.ofNat 7 (\d+)\)\)',line)
                if mm and mm.group(1) not in ("VirtualAssertEQ","VirtualAssertLTE","SD"):
                    dst.add(int(mm.group(2))); last_write[int(mm.group(2))]=ci
        ds=sorted(dst); assert ds==list(range(48,48+len(ds))),(n,ds)
        k=len(ds)
        skip=min(last_write.values())
        used=[r for r in ("rs1","rs2","rs3") if any(f".xreg {r}," in x for x in slots)]
        sparams = f"({' '.join(used)} : regidx) " if used else ""
        sargs = (" " + " ".join(used)) if used else ""
        ex_slot = (slots[0].replace(".xreg rs1", ".xreg x10").replace(".xreg rs2", ".xreg x11")
                   .replace(".xreg rs3", ".xreg x12"))
        ex_args = " ".join({"rs1": "x10", "rs2": "x11", "rs3": "x12"}[r] for r in used)
        slot_lines = ",\n    ".join(", ".join(slots[i:i+3]) for i in range(0,len(slots),3))
        chunk_text="".join(f'''/-- Chunk {i} of `{n}` ({variant}): every row passes the row check for
`{nm}WriteSet`, and the chunk's store slots are the listed ones.
Example: this chunk has {len(cs)} store {"row" if len(cs)==1 else "rows"}. -/
theorem {nm}_chunk{i}
    {params} :
    (Program.seq ({prog}Chunk{i} {args})).rowsWithin ({nm}WriteSet{sargs}) = true ∧
      (Program.seq ({prog}Chunk{i} {args})).storeSlots =
        [{', '.join(cs)}] :=
  ⟨rfl, rfl⟩

''' for i,cs in enumerate(chunk_slots))
        tail=" ++\n      ".join(f"{prog}Chunk{i} {args}" for i in range(skip,nch))
        tailn=nch-skip
        assert tailn in (1,2)
        tail_lemma="Program.resetsPoolCheck_seq_append" if tailn==1 else "Program.resetsPoolCheck_seq_append_append"
        if nch==1:
            ss_proof=f"by\n  unfold {prog} {prog}List\n  rw [({nm}_chunk0 {args}).2]\n  rfl"
            rows_proof=f"({nm}_chunk0 {args}).1"
            rs_proof=f"{nm}_tailResets {args}"
        else:
            f2=",\n      ".join(f"({nm}_chunk{i} {args}).2" for i in range(nch))
            f1=",\n      ".join(f"({nm}_chunk{i} {args}).1" for i in range(nch))
            ss_proof=f"by\n  unfold {prog} {prog}List\n  simp only [Program.storeSlots_seq_append,\n      {f2}]\n  rfl"
            rows_proof=f"by\n    unfold {prog} {prog}List\n    simp only [Program.rowsWithin_seq_append,\n      {f1},\n      Bool.and_self]"
            rs_proof=(f"by\n  unfold {prog} {prog}List\n  exact {tail_lemma} _ ({nm}_tailResets {args})"
                      if nch>tailn else f"{nm}_tailResets {args}")
        out.append(f'''/-! ### `{n}`, {variant} -/

/-- Store slots of `{n}` ({variant}), in row order.
Example: the first slot of `{nm}Stores {ex_args}` is `{ex_slot}`. -/
def {nm}Stores {sparams}: List StoreSlot :=
  [{slot_lines}]

/-- Write set of `{n}` ({variant}): pool registers `vr48..vr{47+k}`, no
architectural register, {len(slots)} store rows.
Example: `{nm}WriteSet {ex_args}` allows the destination `.vreg vr48` and rejects
`.vreg vr{48+k}` and every architectural register other than `x0`. -/
def {nm}WriteSet {sparams}: WriteSet where
  vregs := poolVRegs {k}
  xregs := []
  stores := {nm}Stores{sargs}

{chunk_text}/-- The store slots of the `{n}` rows ({variant}) are exactly `{nm}Stores`.
Example: with `{ex_args}` for the register parameters, the first store row has slot
`{ex_slot}`. -/
theorem {nm}_storeSlots
    {params} :
    ({prog} {args}).storeSlots =
      {nm}Stores{sargs} := {ss_proof}

/-- The `{n}` rows ({variant}) pass the static frame check for `{nm}WriteSet`.
Example: `{nm}_frame` applies `frame_of_run` to this check. -/
theorem {nm}_writesWithin
    {params} :
    ({prog} {args}).WritesWithin
      ({nm}WriteSet{sargs}) :=
  ⟨{rows_proof},
   by rw [{nm}_storeSlots]; exact List.Subset.refl _, rfl⟩

/-- The final chunks of `{n}` ({variant}), which contain the last write of every
pool register, pass the pool-reset check.
Example: in these chunks the last row that writes `vr48` is `ADDI (.vreg vr48) (.xreg x0) 0`. -/
theorem {nm}_tailResets
    {params} :
    (Program.seq ({tail})).resetsPoolCheck (poolVRegs {k}) = true := rfl

/-- The `{n}` rows ({variant}) pass the pool-reset check for `vr48..vr{47+k}`.
Example: with `{nm}_writesWithin`, `Program.resetsPool_of_check` turns it into
`Program.ResetsPool`, so every successful run leaves `vr48` at zero. -/
theorem {nm}_resetsPoolCheck
    {params} :
    ({prog} {args}).resetsPoolCheck (poolVRegs {k}) = true := {rs_proof}

/-- The frame of a successful run of the `{n}` rows ({variant}): only `vr48..vr{47+k}`
and the bytes of the {len(slots)} store slots in `{nm}Stores` may change.
Example: the run leaves `vr32..vr39`, every Sail register, the advice tape and memory
outside the store slots unchanged. -/
theorem {nm}_frame
    {params} {{s s' : SailJoltState}}
    (h : ({prog} {args}).Run s s') :
    Frame ({nm}WriteSet{sargs}) s s' :=
  frame_of_run ({nm}_writesWithin {args}) h
''')
out.append("end JoltISA.Inlines.FrameInstances")
text="\n".join(out)+"\n"
if sys.argv[1:]==["--check"]:
    if OUT.read_text()!=text:
        print(f"{OUT.relative_to(ROOT)} differs from the generator output", file=sys.stderr)
        sys.exit(1)
    print(f"{OUT.relative_to(ROOT)} is up to date")
elif sys.argv[1:]==[]:
    OUT.write_text(text)
else:
    sys.exit("usage: gen_frame_instances.py [--check]")
