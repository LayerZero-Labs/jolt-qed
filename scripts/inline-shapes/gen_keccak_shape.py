#!/usr/bin/env python3
"""Generate JoltBytecode/Inlines/Keccak256/Shape.lean.

The generated rows of KECCAK256 and KECCAK256_ABSORB_PERMUTE
(JoltBytecode/Inlines/Generated/Keccak256.lean and Keccak256AbsorbPermute.lean)
come in chunks of 100 rows. Keccak256/Rows.lean names the blocks of the two
inlines (loads, absorption, 24 rounds of 125 rows, stores, resets). This script
writes, for each chunk, the lemma that the chunk is a run of pieces of those
blocks, where a piece is a block cut with `List.take` and `List.drop` at the
chunk boundaries. Lean checks each lemma by `rfl`; the script only does the
arithmetic of the boundaries, so a wrong cut fails the build.

Usage: scripts/inline-shapes/gen_keccak_shape.py > JoltBytecode/Inlines/Keccak256/Shape.lean
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "JoltBytecode/Inlines/Generated"
CHUNK = 100

ROUNDS = [("roundRows %d" % i, 125) for i in range(24)]
TAIL = [("storeRows rs1", 25), ("resetRows", 37)]
KEYS = [
    # (generated prefix, file, lean name prefix, blocks, rows theorem RHS)
    ("keccak256RowsAuto", "Keccak256.lean", "keccak256",
     [("loadRows rs1", 25)] + ROUNDS + TAIL,
     "loadRows rs1 ++ roundsRows ++ storeRows rs1 ++ resetRows"),
    ("keccak256AbsorbPermuteRowsAuto", "Keccak256AbsorbPermute.lean", "absorbPermute",
     [("loadRows rs1", 25), ("absorbRows rs2", 34)] + ROUNDS + TAIL,
     "loadRows rs1 ++ absorbRows rs2 ++ roundsRows ++ storeRows rs1 ++ resetRows"),
]


def round_constants():
    text = (ROOT / "JoltBytecode/Inlines/Keccak256/Rows.lean").read_text()
    body = text[text.index("def roundConstants"):]
    body = body[body.index("[") + 1:body.index("]")]
    rcs = re.findall(r"0x[0-9a-f]{16}", body)
    assert len(rcs) == 24, rcs
    return rcs


def chunk_count(prefix, fname):
    text = (GEN / fname).read_text()
    n = len(re.findall(r"^def %sChunk\d+ " % prefix, text, re.M))
    rd = len(re.findall(r"^def %sRdZeroChunk\d+ " % prefix, text, re.M))
    assert n == rd, (prefix, n, rd)
    return n


def paren(term):
    return "(%s)" % term if " " in term else term


def wrap(items, indent="    ", first=8):
    """Join `items` with ", ", breaking lines before 100 columns."""
    lines, cur, width = [], [], first
    for it in items:
        if cur and width + len(it) + 2 > 98:
            lines.append(", ".join(cur) + ",")
            cur, width = [], len(indent)
        cur.append(it)
        width += len(it) + 2
    lines.append(", ".join(cur))
    return ("\n" + indent).join(lines)


def rterm(term):
    """The block as it reads after `generalize roundRows = R`."""
    return term.replace("roundRows", "R")


def piece(term, size, lo, hi):
    """The rows lo..hi-1 of a block of `size` rows."""
    if lo == 0 and hi == size:
        return term
    if lo == 0:
        return "%s.take %d" % (paren(term), hi)
    if hi == size:
        return "%s.drop %d" % (paren(term), lo)
    return "(%s.drop %d).take %d" % (paren(term), lo, hi - lo)


def layout(blocks, nchunks):
    """Pieces of each chunk, and the cut points inside each block."""
    starts = []
    pos = 0
    for term, size in blocks:
        starts.append(pos)
        pos += size
    total = pos
    assert (total + CHUNK - 1) // CHUNK == nchunks, (total, nchunks)
    chunks = []
    for k in range(nchunks):
        lo, hi = k * CHUNK, min((k + 1) * CHUNK, total)
        ps = []
        for (term, size), st in zip(blocks, starts):
            a, b = max(lo, st), min(hi, st + size)
            if a < b:
                ps.append(piece(term, size, a - st, b - st))
        chunks.append(ps)
    cuts = []
    for (term, size), st in zip(blocks, starts):
        cs = [c - st for c in range(CHUNK, total, CHUNK) if st < c < st + size]
        if cs:
            cuts.append((term, cs))
    return total, chunks, cuts


def main():
    out = []
    w = out.append
    w("""import JoltBytecode.Inlines.Keccak256.Rows

/-!
# The generated Keccak rows are the blocks of `Keccak256.Rows`

Generated by `scripts/inline-shapes/gen_keccak_shape.py`; do not edit by hand.

Each `chunkN_eq` says that chunk `N` of the generated rows (100 rows) is a run of pieces of the
blocks of `Keccak256.Rows`, and Lean checks it by `rfl`. A round has 125 rows, so every chunk
boundary inside the rounds cuts a round, and the pieces are rounds cut with `List.take` and
`List.drop`. `keccak256RowsAutoList_eq` and `absorbPermuteRowsAutoList_eq` reassemble the
chunks with `split2` and `split3`. The `rd = x0` rows are the same rows, chunk by chunk.
-/

open Sail Sail.ConcurrencyInterfaceV1 Sail.ConcurrencyInterfaceV1.PreSail LeanRV64D
  LeanRV64D.Functions JoltISA.Inlines.Generated

set_option autoImplicit false

namespace JoltISA.Inlines.Keccak256

/-- A list is its first `c` elements followed by the rest. -/
theorem split2 {α : Type} (l : List α) (c : Nat) : l = l.take c ++ l.drop c :=
  (List.take_append_drop c l).symm

/-- A list cut at `c ≤ d` into three pieces. -/
theorem split3 {α : Type} (l : List α) (c d : Nat) (h : c ≤ d) :
    l = l.take c ++ ((l.drop c).take (d - c) ++ l.drop d) := by
  have hd : (l.drop c).drop (d - c) = l.drop d := by
    rw [List.drop_drop, Nat.add_sub_cancel' h]
  rw [← hd, List.take_append_drop, List.take_append_drop]

/-- The 24 rounds, one after another. -/
theorem roundsRows_split : roundsRows =
    """ + " ++\n      ".join("roundRows %d" % i for i in range(24)) + """ := by
  simp only [roundsRows, List.range_succ, List.range_zero, List.nil_append, List.flatMap_append,
    List.flatMap_cons, List.flatMap_nil, List.append_nil, List.append_assoc]
""")
    for i, rc in enumerate(round_constants()):
        w("""
private theorem roundRows_eq%d : roundRows %d = (roundOps %s).map Op.toInstr := rfl
""" % (i, i, rc))
    for prefix, fname, name, blocks, rhs in KEYS:
        n = chunk_count(prefix, fname)
        total, chunks, cuts = layout(blocks, n)
        title = "KECCAK256" if name == "keccak256" else "KECCAK256_ABSORB_PERMUTE"
        w("\n/-! ## `%s` (%d rows, %d chunks) -/\n\n" % (title, total, n))
        for k, ps in enumerate(chunks):
            rounds = sorted({int(m) for p in ps for m in re.findall(r"roundRows (\d+)", p)})
            if rounds:
                proof = "by\n  simp only [%s]\n  rfl" % ", ".join("roundRows_eq%d" % i for i in rounds)
            else:
                proof = "rfl"
            w("""/-- Chunk %d of the generated `%s` rows as pieces of blocks. -/
theorem %s_chunk%d_eq (rs1 rs2 rs3 : regidx) :
    %sChunk%d rs1 rs2 rs3 =
      %s := %s

""" % (k, title, name, k, prefix, k, " ++\n      ".join(ps), proof))
        for k in range(n):
            w("""private theorem %s_rdZeroChunk%d_eq (rs1 rs2 rs3 : regidx) :
    %sRdZeroChunk%d rs1 rs2 =
      %sChunk%d rs1 rs2 rs3 := rfl

""" % (name, k, prefix, k, prefix, k))
        rws = []
        for term, cs in cuts:
            if len(cs) == 1:
                rws.append("split2 (%s) %d" % (rterm(term), cs[0]))
            else:
                assert len(cs) == 2
                rws.append("split3 (%s) %d %d (by omega)" % (rterm(term), cs[0], cs[1]))
        chunk_eqs = wrap(["%s_chunk%d_eq" % (name, k) for k in range(n)])
        w("""/-- **The generated `%s` rows are the blocks of `Keccak256.Rows`.** -/
theorem %sRowsAutoList_eq (rs1 rs2 rs3 : regidx) :
    %sList rs1 rs2 rs3 =
      %s := by
  unfold %sList
  rw [%s,
    roundsRows_split]
  -- Cut the rounds on the right as the chunks cut them. `roundRows` is generalized first, so
  -- that `rw` does not unfold one round to compare it with another.
  generalize roundRows = R
  conv_rhs => rw [%s]
  simp only [List.append_assoc]
""" % (title, name, prefix, rhs, prefix, chunk_eqs, ",\n    ".join(rws)))
        rd_eqs = wrap(["%s_rdZeroChunk%d_eq rs1 rs2 rs3" % (name, k) for k in range(n)])
        w("""
/-- The `rd = x0` rows of `%s` are the `rd ≠ x0` rows: the inline never
reads `rd`. -/
theorem %sRowsAutoRdZeroList_eq (rs1 rs2 rs3 : regidx) :
    %sRdZeroList rs1 rs2 =
      %sList rs1 rs2 rs3 := by
  unfold %sRdZeroList %sList
  rw [%s]
""" % (title, name, prefix, prefix, prefix, prefix, rd_eqs))
    w("\nend JoltISA.Inlines.Keccak256\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
